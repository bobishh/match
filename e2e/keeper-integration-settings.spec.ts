test("Given future boards are off, when owner enables them, then policy-only request asks both sides to approve without rejoining current boards", async ({ page }) => {
  await page.goto("/")
  await page.evaluate(async () => (await import("/e2e/support/keeperSettings.ts")).mountKeeperSettings("off"))
  await page.getByRole("list", { name: "Keeper services" }).getByRole("button", { name: /Rusty keeper/ }).click()
  await page.getByRole("button", { name: "Manage board access" }).click()
  await expect(page.getByRole("checkbox", { name: "Include future boards" })).not.toBeChecked()
  await page.getByRole("checkbox", { name: "Include future boards" }).check()
  await page.getByRole("button", { name: "Request future-board approval" }).click()
  await expect(page.getByText("518407")).toBeVisible()
  await expect(page.getByText("Both the operator and owner must approve this code before future-board policy changes.")).toBeVisible()
  await expect(page.getByRole("status", { name: "Current integration access" })).toContainText("Current access stays active: Current board")
  await expect(page.getByRole("checkbox", { name: "Keeper board: Current board" })).toHaveCount(0)
  await page.getByRole("button", { name: "Code matches · approve" }).click()
  await expect(page.getByText("Future boards enabled. Current board access remains active.")).toBeVisible()
  await expect(page.getByRole("status", { name: "Current integration access" })).toContainText("Current board")
})

test("Given the last board scope is gone, when owner reloads keeper list, then settings and manual board approval remain available", async ({ page }) => {
  await page.goto("/")
  await page.evaluate(async () => (await import("/e2e/support/keeperSettings.ts")).mountKeeperSettings("empty"))
  const list = page.getByRole("list", { name: "Keeper services" })
  const keeper = list.getByRole("button", { name: /Rusty keeper/ })
  await expect(keeper).toContainText("No boards · not connected to this board")
  await keeper.click()
  await page.getByRole("button", { name: "Manage board access" }).click()
  await page.getByRole("checkbox", { name: "Include future boards" }).check()
  await page.getByRole("button", { name: "Request future-board approval" }).click()
  await expect(page.getByRole("status", { name: "Current integration access" })).toContainText("no active boards")
  await page.getByRole("button", { name: "Code matches · approve" }).click()
  await expect(page.getByText("Future boards enabled. No board access added.")).toBeVisible()
  await page.getByRole("button", { name: "Back" }).click()
  await page.getByRole("button", { name: /Add keeper/ }).click()
  await page.getByRole("textbox", { name: "Keeper hostname" }).fill("http://127.0.0.1:4244")
  await page.getByRole("button", { name: "Discover keeper" }).click()
  await expect(page.getByRole("checkbox", { name: "Keeper board: New board" })).toBeChecked()
  await page.getByRole("checkbox", { name: "Keeper board: Current board" }).uncheck()
  await page.getByRole("checkbox", { name: "Keeper board: Existing unselected board" }).uncheck()
  await page.getByRole("button", { name: "Request access" }).click()
  await expect(page.getByText("611204")).toBeVisible()
  await expect(page.getByRole("checkbox", { name: "Keeper board: New board" })).toBeChecked()
})

