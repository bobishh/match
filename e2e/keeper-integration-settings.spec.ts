import { expect, test } from "./support/coverage"
test("Given an active Rusty integration, when owner disables future boards, then current access remains active", async ({ page }) => {
  await page.goto("/")
  await page.evaluate(async () => (await import("/e2e/support/keeperSettings.ts")).mountKeeperSettings())
  const list = page.getByRole("list", { name: "Keeper services" })
  await list.getByRole("button", { name: /Rusty keeper/ }).click()
  await page.getByRole("button", { name: "Manage board access" }).click()
  await expect(page.getByRole("checkbox", { name: "Include future boards" })).toBeChecked()
  await page.getByRole("checkbox", { name: "Include future boards" }).uncheck()
  await page.getByRole("button", { name: "Save future-board setting" }).click()
  await expect(page.getByRole("status", { name: "Keeper settings status" })).toContainText("Future boards are off. Current board access remains active.")
  await expect(page.getByText("Current board", { exact: true })).toBeVisible()
  await expect(page.getByText("Existing unselected board", { exact: true })).toHaveCount(0)
})

